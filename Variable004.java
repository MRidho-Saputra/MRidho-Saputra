package Variable;
public class Variable004 {
    public static void main(String[] args) {
        //deklarasi variabel
        int Bilangan1, Bilangan2;
        int hasil_jumlah, hasil_kurang, hasil_kali, hasil_bagi;

        Bilangan1 = 10;
        Bilangan2 = 2;

        hasil_jumlah = Bilangan1 + Bilangan2;
        hasil_kurang = Bilangan1 - Bilangan2;
        hasil_kali = Bilangan1 * Bilangan2;
        hasil_bagi = Bilangan1 / Bilangan2;

        System.out.println(hasil_jumlah);
        System.out.println(hasil_kurang);
        System.out.println(hasil_kali);
        System.out.println(hasil_bagi);
        

    }
}
